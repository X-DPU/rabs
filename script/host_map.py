#!/usr/bin/env python3
"""host_map.py -- host-view (PCIe BAR2) addresses of the app's compute units.

    host_map.py <kernel.xsa | *.hwh> <out.h>

Reads the linked design's hardware hand-off (inside the v++ kernel.xsa, or a bare .hwh) and
writes one macro per slave segment reachable from the host master (CPM_PCIE_NOC_0), in the
SAME form fpga/vivado/shell_address.sh uses for the shell:

    #define SEG_<INSTANCE>_<BLOCK>_BASE_ADDRESS  0x202000F0000ULL

so the host driver can take an app kernel's register base (e.g. the RDMA qp_setup /
dm_rd / dm_wr CUs after they left the shell, doc/secure-shell.md section 6) through the
same ODPU_BAR2_OFF() it uses for shell blocks. Segments the shell already publishes are
skipped (the shell header owns them); only CUs the link added appear here.
"""
import re, sys, zipfile, io

def read_hwh(path):
    if path.endswith('.hwh'):
        return open(path, 'r', errors='replace').read()
    with zipfile.ZipFile(path) as z:
        names = [n for n in z.namelist() if n.endswith('.hwh') and '/' not in n.strip('/')]
        if not names:
            names = [n for n in z.namelist() if n.endswith('.hwh')]
        if not names:
            sys.exit(f"{path}: no .hwh inside")
        # the top-level design hand-off is the largest one
        names.sort(key=lambda n: z.getinfo(n).file_size, reverse=True)
        return z.read(names[0]).decode('utf-8', errors='replace')

def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    hwh = read_hwh(src)
    rx = re.compile(r'<MEMRANGE\s+([^>]*)/>')
    attr = re.compile(r'(\w+)="([^"]*)"')
    segs = {}
    for m in rx.finditer(hwh):
        a = dict(attr.findall(m.group(1)))
        if a.get('MASTERBUSINTERFACE') != 'CPM_PCIE_NOC_0':
            continue
        if a.get('MEMTYPE') != 'REGISTER':
            continue
        inst = a.get('INSTANCE', '')
        blk = a.get('ADDRESSBLOCK', 'Reg')
        base = int(a['BASEVALUE'], 16)
        high = int(a['HIGHVALUE'], 16)
        name = re.sub(r'[^A-Za-z0-9]', '_', f"{inst}_{blk}").upper()
        segs.setdefault(name, (base, high, inst, a.get('SLAVEBUSINTERFACE', '')))
    lines = ["/* generated by app/mk/script/host_map.py from %s -- do not edit */" % src.split('/')[-1],
             "#ifndef OPENDPU_APP_HOST_MAP_H", "#define OPENDPU_APP_HOST_MAP_H",
             "#define ODPU_APP_HOST_MAP 1", ""]
    for name in sorted(segs, key=lambda n: segs[n][0]):
        base, high, inst, sbi = segs[name]
        lines.append("/* %s/%s */" % (inst, sbi))
        lines.append("#ifndef SEG_%s_BASE_ADDRESS" % name)
        lines.append("#define SEG_%s_BASE_ADDRESS 0x%XULL" % (name, base))
        lines.append("#define SEG_%s_HIGH_ADDRESS 0x%XULL" % (name, high))
        lines.append("#endif")
    lines += ["", "#endif /* OPENDPU_APP_HOST_MAP_H */", ""]
    open(out, 'w').write("\n".join(lines))
    print("host_map.py: %d host-visible register segments -> %s" % (len(segs), out))

if __name__ == '__main__':
    main()
